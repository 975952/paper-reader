/**
 * 论文操作目录。
 *
 * 设计立场（来自调研）：
 *   · 不做「一个万能按钮」，而是**一排可按需调用的操作** —— 读论文时想干什么是随时在变的；
 *   · 每个操作 = 一次带独立 system prompt 的调用，输入是论文（全文 / 阅读索引）；
 *   · coach 模式是**其中一种模式**，按需开启，不是默认入口（见 docs/paper-explainer-plan.md）。
 *
 * 所有操作共享同一条底线（COMMON_RULES）：
 *   只依据给定材料、标页码、不编造、不空夸。
 */

